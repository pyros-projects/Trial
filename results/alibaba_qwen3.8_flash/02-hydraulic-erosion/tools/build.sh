#!/usr/bin/env bash
# Assembles the self-contained index.html from src/.
#   src/shell.html  document skeleton, CSS, markup
#   src/sim.js      simulation core (no DOM)
#   src/render.js   WebGL2 renderer + Canvas2D fallback
#   src/app.js      UI, camera, input, render loop
set -euo pipefail
cd "$(dirname "$0")/.."

for f in src/sim.js src/render.js src/app.js src/shell.html; do
  if grep -q "</content>\|</tool_use>\|antml" "$f"; then
    echo "ERROR: $f contains stray tooling artifacts" >&2
    exit 1
  fi
done

BUNDLE=$(mktemp /tmp/hal-bundle-XXXX.js)
{
  echo '(() => {'
  echo 'const LAB = {};'
  sed '1,/^const LAB = {};$/d' src/sim.js
  echo ''
  echo '/* ---------- renderer ---------- */'
  cat src/render.js
  echo ''
  echo '/* ---------- application ---------- */'
  cat src/app.js
  echo '})();'
} > "$BUNDLE"

node --check "$BUNDLE"
echo "bundle syntax OK"

{
  cat src/shell.html
  echo '<script>'
  echo '"use strict";'
  echo '/* Self-contained build generated by tools/build.sh.'
  echo '   Sources: src/sim.js (model), src/render.js (view), src/app.js (controller). */'
  cat "$BUNDLE"
  echo '</script>'
  echo '</body>'
  echo '</html>'
} > index.html

rm -f "$BUNDLE"
echo "index.html: $(wc -c < index.html) bytes / $(wc -l < index.html) lines"
