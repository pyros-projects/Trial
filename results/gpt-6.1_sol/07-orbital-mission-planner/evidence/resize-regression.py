from browser_helpers import *
from cdp_input import Input

ab('open','http://127.0.0.1:8843/index.html')
ab('set','viewport',1280,800)
click('Pause simulation')
saved=data()
check('desktop workspace fits 1280 by 800',data('document.querySelector(".center").getBoundingClientRect().bottom<=800 && document.querySelector(".header").getBoundingClientRect().top===0'))
ab('set','viewport',390,844)
c=Input();c.mobile()
ab('wait','--fn','devicePixelRatio===3 && document.getElementById("space").width===1170')
check('DPR-only mobile transition rebuilds Canvas resolution',data('document.getElementById("space").width===1170 && document.getElementById("space").height===1215'))
ab('click','#mobile-telemetry')
check('visible telemetry plot uses current pixel ratio',data('document.getElementById("altitude-plot").width===Math.round(document.getElementById("altitude-plot").getBoundingClientRect().width*3)'))
camera=data()['camera']
c.touch('touchStart',[(110,300)]);c.touch('touchMove',[(140,315)]);c.touch('touchEnd',[])
check('absolute Canvas retains native touch pan',abs(data()['camera']['x']-camera['x'])>1)
scale=data()['camera']['scale']
c.touch('touchStart',[(110,320),(280,320)]);c.touch('touchMove',[(80,320),(310,320)]);c.touch('touchEnd',[])
check('absolute Canvas retains native pinch zoom',data()['camera']['scale']>scale*1.2)
click('Focus selected body')
screenshot('33-final-mobile-dpr3.png')
ab('click','#mobile-systems');ab('scroll','down',900)
check('mobile page is scrolled before resize regression',data('scrollY')>100)
screenshot('34-resize-mobile-scrolled.png')
c.close();ab('set','viewport',1440,900)
ab('wait','--fn','document.querySelector(".center").getBoundingClientRect().bottom<=900 && document.querySelector(".header").getBoundingClientRect().top===0')
check('mobile to desktop restores visible header and bounded workspace',data('scrollY===0 && document.documentElement.scrollHeight===900 && document.querySelector(".viewport").getBoundingClientRect().height===607'))
check('DPR backing dimensions cannot stretch desktop grid',data('document.getElementById("space").height===607 && document.querySelector(".center").getBoundingClientRect().height===764'))
check('resize preserves paused physical state',data()['time']==saved['time'] and data()['bodies']==saved['bodies'])
ab('click','#tab-telemetry');click('Focus selected body')
screenshot('35-final-desktop-1440x900.png')
scale=data()['camera']['scale'];ab('focus','#space');ab('press','+')
check('Canvas keyboard zoom retains input after resize',data()['camera']['scale']>scale)
click('Play simulation');ab('wait','--fn',f'window.orbitLab.getState().time>{saved["time"]+1}');click('Pause simulation')
check('simulation resumes after cross-size resize',data()['time']>saved['time']+1 and data()['paused'])
check('resize regression has no uncaught errors',ab('errors')=='')
check('resize regression console clean',ab('console')=='')
print('Final resize regression completed',flush=True)
