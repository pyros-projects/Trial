const fs = require('fs');
const vm = require('vm');
const assert = require('node:assert/strict');
const path = require('path');
const file = path.join(__dirname, '../index.html');
assert.ok(fs.existsSync(file), 'Delivered application index.html must exist');
const html = fs.readFileSync(file,'utf8');
const src = html.match(/<script id="physics">([\s\S]*?)<\/script>/);
assert.ok(src, 'Embedded numerical core must exist');
const context = {window:{}};
vm.runInNewContext(src[1],context);
const P=context.window.Physics;
const opts={...P.defaults, spin:0, steps:600, rayStep:0.03};
const straight=P.trace([0,0,18],[0,0,-1],{...opts,strength:0,horizon:0.01});
assert.ok(straight.deflection < 1e-8,'Zero strength ray must remain straight');
const center=P.trace([0,0,18],[0,0,-1],opts);
assert.equal(center.outcome,'Captured','Central ray must fall through horizon');
const d=P.normalize([5.3,0,-18]);
const weak=P.trace([0,0,18],d,{...opts,strength:0.1});
const strong=P.trace([0,0,18],d,opts);
assert.equal(strong.outcome,'Escaped');
assert.ok(strong.deflection>weak.deflection+0.1,'Mass must bend escaping background rays');
const finer=P.trace([0,0,18],d,{...opts,rayStep:0.015});
assert.ok(Math.abs(finer.deflection-strong.deflection)<0.03,'Halving ray step must converge');
const approach=P.factors([4,0,0],[0,0,-1],opts);
const recede=P.factors([-4,0,0],[0,0,-1],opts);
assert.ok(approach.doppler>recede.doppler,'Approaching gas must have larger Doppler factor');
assert.ok(approach.gravity<1 && approach.gravity>0,'Gravity must redshift disk emission');
const sanitized=P.sanitize({...P.defaults,inner:1,outer:1,horizon:2,steps:2,exposure:NaN});
assert.ok(sanitized.inner>sanitized.horizon && sanitized.outer>sanitized.inner);
assert.ok(sanitized.steps>=80 && Number.isFinite(sanitized.exposure));
console.log('PASS: straight/capture/bending/convergence/Doppler/redshift/constraints');
console.log(JSON.stringify({strongBending:strong.deflection,weakBending:weak.deflection,fineBending:finer.deflection,steps:strong.steps,approach,recede}));
